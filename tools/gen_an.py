# ---------- власна арифметика генератора (без sympy) ----------
def det(m):
    m = [[F(v) for v in row] for row in m]
    n = len(m)
    if n == 1:
        return m[0][0]
    if n == 2:
        return m[0][0] * m[1][1] - m[0][1] * m[1][0]
    s = F(0)
    for j in range(n):
        minor = [row[:j] + row[j + 1:] for row in m[1:]]
        s += (-1) ** j * m[0][j] * det(minor)
    return s


def cofactor(m, i, j):
    minor = [row[:j] + row[j + 1:] for k, row in enumerate(m) if k != i]
    return (-1) ** (i + j) * det(minor)


def inverse(m):
    n = len(m)
    d = det(m)
    return [[cofactor(m, j, i) / d for j in range(n)] for i in range(n)]


def matmul(a, b):
    return [[sum(F(a[i][k]) * F(b[k][j]) for k in range(len(b))) for j in range(len(b[0]))]
            for i in range(len(a))]


def matadd(*ms):
    return [[sum(m[i][j] for m in ms) for j in range(len(ms[0][0]))] for i in range(len(ms[0]))]


def scal(c, m):
    return [[c * v for v in row] for row in m]


def eye(n):
    return [[1 if i == j else 0 for j in range(n)] for i in range(n)]


def sub(a, b):
    return [p - q for p, q in zip(a, b)]


def dot(a, b):
    return sum(p * q for p, q in zip(a, b))


def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], -(a[0] * b[2] - a[2] * b[0]), a[0] * b[1] - a[1] * b[0]]


def norm(a):
    return math.sqrt(dot(a, a))


def rank(m):
    m = [[F(v) for v in row] for row in m]
    r = 0
    rows, cols = len(m), len(m[0])
    for c in range(cols):
        piv = next((i for i in range(r, rows) if m[i][c] != 0), None)
        if piv is None:
            continue
        m[r], m[piv] = m[piv], m[r]
        for i in range(rows):
            if i != r and m[i][c] != 0:
                k = m[i][c] / m[r][c]
                m[i] = [a - k * b for a, b in zip(m[i], m[r])]
        r += 1
    return r


def mstr(m):
    return "Matrix(" + str([[int(v) if F(v).denominator == 1 else f"Rational({F(v).numerator},{F(v).denominator})"
                              for v in row] for row in m]).replace("'", "") + ")"


