def acc(*cores):
    out = []
    for c in cores:
        for pre in ("", "називається ", "це "):
            s = pre + c
            if s not in out:
                out.append(s)
    return out


def short(qid, topic, q, answer, cores, explain, src):
    Q.append({"id": qid, "topic": topic, "type": "short", "q": q, "answer": answer,
              "accept": acc(*cores), "explain": explain, "src": src})


