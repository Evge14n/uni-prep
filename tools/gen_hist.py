def parse_uni2():
    """46 тестових питань з UNI2 історії."""
    lines = SRC["uni2"].read_text(encoding="utf-8").splitlines()
    letters = "абвг"
    found = []
    for i, line in enumerate(lines):
        m = re.match(r"\*\*(\d)\.(\d+)\.\*\* (.+)$", line)
        if not m:
            continue
        theme, num, q = int(m.group(1)), int(m.group(2)), m.group(3).strip()
        opt_line = lines[i + 1].strip()
        ans_line = lines[i + 2].strip()
        parts = re.split(r"(?:^|\s+)([абвг])\)\s+", opt_line)
        opts = {parts[j]: parts[j + 1].strip() for j in range(1, len(parts) - 1, 2)}
        if list(opts) != list(letters[:len(opts)]) or len(opts) < 3:
            ERRORS.append(f"UNI2 {theme}.{num}: не розібрав варіанти «{opt_line}»")
            continue
        ma = re.match(r"Відповідь: \*\*([абвг])\*\*\.\s*(.+)$", ans_line)
        if not ma:
            ERRORS.append(f"UNI2 {theme}.{num}: не розібрав відповідь «{ans_line}»")
            continue
        expl = ma.group(2).strip()
        mark = re.search(r"\s*(\[[^\]]*\]|\(ЕІУ:[^)]*\))\s*$", expl)
        src_mark = ""
        if mark:
            src_mark = mark.group(1)
            expl = expl[: mark.start()].strip()
        found.append({
            "topic": TOPIC[theme], "type": "single", "q": q.replace("**", ""),
            "options": list(opts.values()), "answer": letters.index(ma.group(1)),
            "explain": expl.replace("**", ""),
            "src": f"UNI2 історії, тест {theme}.{num} {src_mark}".strip(),
        })
    return found


def th(theme, q, options, answer, explain, key, proof, keep=False):
    """Нове питання: proof мусить бути дослівно у файлі-джерелі key."""
    proofs = proof if isinstance(proof, list) else [proof]
    for p in proofs:
        if norm(p) not in TEXT.get(key, ""):
            ERRORS.append(f"{TOPIC[theme]}: «{q[:50]}»: уривка «{p}» нема у {SRC[key].name}")
    item = {"topic": TOPIC[theme], "type": "single", "q": q, "options": options,
            "answer": answer, "explain": explain, "src": SRC_LABEL[key]}
    if keep:
        item["keepOrder"] = True
    QS.append(item)


def points(grades, verify, explain):
    """Бали за залік = середнє × 20. Python (Fraction) і sympy (verify) мусять збігтися."""
    py = Fraction(sum(grades), len(grades)) * 20
    sv = sp.sympify(eval(verify, {"__builtins__": {}}, NS))  # noqa: S307
    if sp.Rational(py.numerator, py.denominator) != sv:
        ERRORS.append(f"бали {grades}: python {py} ≠ verify {sv}")
    if py.denominator != 1:
        ERRORS.append(f"бали {grades}: не ціле {py}")
    QS.append({"topic": TOPIC[0], "type": "number",
               "q": f"Оцінки за семестр: {', '.join(map(str, grades))}. Скільки балів за залік "
                    "(середнє з усіх оцінок × 20)?",
               "answer": int(py), "tol": 0.001, "calc": True, "verify": verify,
               "explain": explain, "src": SRC_LABEL["rules"]})


