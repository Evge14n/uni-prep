def main():
    errs = []
    out = []
    for i, q in enumerate(Q, 1):
        q = dict(q)
        q["id"] = f"k2-{i:03d}"
        gen = q.pop("gen", None)
        where = q["id"]
        if q.get("calc"):
            if gen is None or "verify" not in q:
                errs.append(f"{where}: calc без gen/verify")
            else:
                g = ev(gen)
                if q["type"] == "number":
                    if abs(float(sp.N(g)) - q["answer"]) > q.get("tol", 0.01) * max(1.0, abs(q["answer"])):
                        errs.append(f"{where}: gen={sp.N(g)} ≠ answer={q['answer']}")
                else:
                    if not same(g, ev(q["value"])):
                        errs.append(f"{where}: gen={g} ≠ value={q['value']}")
                    ov = q.get("optionValues")
                    if ov:
                        for j, s in enumerate(ov):
                            if s is None:
                                continue
                            eq = same(ev(s), ev(q["value"]))
                            if (j == q["answer"]) != eq:
                                errs.append(f"{where}: optionValues[{j}] не так (правильний={j == q['answer']})")
        if q["type"] in ("single", "multi") and len(set(q["options"])) != len(q["options"]):
            errs.append(f"{where}: однакові варіанти")
        order = ["id", "topic", "type", "q", "pre", "options", "keepOrder", "answer", "accept", "tol",
                 "calc", "verify", "value", "optionValues", "explain", "explainPre", "src"]
        out.append({k: q[k] for k in order if k in q})
    text = json.dumps({"questions": out}, ensure_ascii=False, indent=1)
    for b in BAD:
        if b in text:
            errs.append(f"заборонене «{b}» у quiz.json")
    if errs:
        print("ПОМИЛКИ:")
        for e in errs:
            print("  ", e)
        return 1
    OUT.write_text(text + "\n", encoding="utf-8")
    n_calc = sum(1 for q in out if q.get("calc"))
    types = {}
    topics = {}
    for q in out:
        types[q["type"]] = types.get(q["type"], 0) + 1
        topics[q["topic"]] = topics.get(q["topic"], 0) + 1
    print(f"OK: {len(out)} питань, calc {n_calc}, теорія {len(out) - n_calc} -> {OUT}")
    print("типи:", types)
    print("теми:", len(topics))
    for k, v in topics.items():
        print(f"   {v:3}  {k}")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
