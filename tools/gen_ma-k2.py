def same(a, b):
    a, b = sp.sympify(a), sp.sympify(b)
    try:
        if sp.simplify(a - b) == 0:
            return True
    except Exception:  # noqa: BLE001
        pass
    try:
        return abs(complex(sp.N(a, 30)) - complex(sp.N(b, 30))) <= 1e-9 * max(1.0, abs(complex(sp.N(b, 30))))
    except Exception:  # noqa: BLE001
        return False


