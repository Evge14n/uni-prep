def th(topic, q, options, answer, explain, src, keep=False, pre=None):
    """Теоретичне питання: single (answer - індекс) або multi (answer - список)."""
    d = {"topic": topic, "type": "multi" if isinstance(answer, list) else "single", "q": q,
         "options": options, "answer": answer, "explain": explain, "src": src}
    if keep:
        d["keepOrder"] = True
    if pre:
        d["pre"] = pre
    _add(d)


def num(topic, q, ans, explain, src, verify=None, tol=None):
    """Введення числа. ans - sympy-обʼєкт, порахований тут; verify - інший шлях."""
    val = sp.N(ans)
    answer = int(val) if same(val, sp.Integer(round(float(val)))) else round(float(val), 6)
    d = {"topic": topic, "type": "number", "q": q, "answer": answer, "explain": explain, "src": src}
    if verify:
        got = ev(verify)
        assert same(got, ans, 1e-6), (q, got, ans)
        d["calc"] = True
        d["verify"] = verify
    if tol is not None:
        d["tol"] = tol
    _add(d)


def calc1(topic, q, options, opt_values, ans, verify, explain, src, pre=None):
    """Один варіант з числовою перевіркою. Правильний індекс знаходить код."""
    assert len(options) == len(opt_values)
    hits = [i for i, s in enumerate(opt_values) if s is not None and same(ev(s), ans)]
    assert len(hits) == 1, (q, hits, ans)
    got = ev(verify)
    assert same(got, ans), (q, got, ans)
    value = sp.sstr(ans)
    assert same(ev(value), ans), (q, value)
    d = {"topic": topic, "type": "single", "q": q, "options": options, "answer": hits[0],
         "calc": True, "verify": verify, "value": value, "optionValues": opt_values,
         "explain": explain, "src": src}
    if pre:
        d["pre"] = pre
    _add(d)


