def ev(s):
    return sp.sympify(eval(s, {"__builtins__": {}}, NS))  # noqa: S307 - лише наші рядки


def same(p, q, tol=1e-9):
    p, q = sp.sympify(p), sp.sympify(q)
    try:
        if sp.simplify(p - q) == 0:
            return True
    except Exception:  # noqa: BLE001
        pass
    try:
        fp, fq = complex(sp.N(p, 30)), complex(sp.N(q, 30))
        return abs(fp - fq) <= tol * max(1.0, abs(fq))
    except Exception:  # noqa: BLE001
        return False


