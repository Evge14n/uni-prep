NS = {name: getattr(sp, name) for name in dir(sp) if not name.startswith("_")}
NS.update({"e": sp.E, "E": sp.E, "pi": sp.pi, "oo": sp.oo, "ln": sp.log})
for _s in "x y z t u v w a b c n k m h r s".split():
    NS[_s] = sp.Symbol(_s, real=True)


def val(expr):
    return float(sp.N(sp.sympify(eval(expr, {"__builtins__": {}}, NS)), 20))  # noqa: S307


def close(p, q, rel):
    return abs(p - q) <= rel * max(abs(q), 1e-300)


SUP = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")


def fmt(xv, sig=3):
    """Число українською: кома, 10ⁿ для дуже великих і малих."""
    xv = float(xv)
    if xv == 0:
        return "0"
    ax = abs(xv)
    if ax >= 1e5 or ax < 1e-3:
        ex = math.floor(math.log10(ax))
        ma = round(xv / 10 ** ex, sig - 1)
        if abs(ma) >= 10:
            ma /= 10
            ex += 1
        ms = f"{ma:.{sig - 1}f}".rstrip("0").rstrip(".")
        return ms.replace(".", ",") + "·10" + str(ex).translate(SUP)
    if ax >= 100:
        return str(int(round(xv)))
    d = sig - 1 - math.floor(math.log10(ax))
    st = f"{round(xv, d):.{d}f}"
    if "." in st:
        st = st.rstrip("0").rstrip(".")
    return st.replace(".", ",")


def rnd(xv, sig=4):
    return float(f"{xv:.{sig}g}")


QS = []


def _base(topic, q, explain, src):
    return {"id": f"mech-{len(QS) + 1:03d}", "topic": topic, "q": q, "explain": explain, "src": src}


def T(topic, q, options, explain, src, answer=0, keep=False):
    """Теоретичне питання з одним правильним варіантом."""
    d = _base(topic, q, explain, src)
    d.update({"type": "single", "options": options, "answer": answer})
    if keep:
        d["keepOrder"] = True
    QS.append(d)


def SH(topic, q, answer, accept, explain, src):
    d = _base(topic, q, explain, src)
    d.update({"type": "short", "answer": answer, "accept": accept})
    QS.append(d)


def NUM(topic, q, expr, verify, explain, src, tol=0.02, sig=4):
    """Числова відповідь: expr - шлях генератора, verify - незалежний шлях."""
    pa, pb = val(expr), val(verify)
    assert close(pa, pb, 1e-6), (q, pa, pb)
    d = _base(topic, q, explain, src)
    d.update({"type": "number", "answer": rnd(pa, sig), "tol": tol, "calc": True, "verify": verify})
    QS.append(d)


def CS(topic, q, exprs, unit, verify, explain, src, labels=None, sig=3):
    """Вибір з числових варіантів. exprs[0] - правильний, решта - типові помилки."""
    vals = [val(e_) for e_ in exprs]
    assert close(vals[0], val(verify), 1e-6), (q, vals[0], val(verify))
    for vv in vals[1:]:
        assert not close(vv, vals[0], 1e-6), (q, "дистрактор = відповідь")
    opts = labels or [fmt(vv, sig) + (" " + unit if unit else "") for vv in vals]
    assert len(set(opts)) == len(opts), (q, opts)
    d = _base(topic, q, explain, src)
    d.update({"type": "single", "options": opts, "answer": 0, "calc": True,
              "verify": verify, "value": exprs[0], "optionValues": exprs})
    QS.append(d)


