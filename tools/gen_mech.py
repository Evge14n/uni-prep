NUMRE = re.compile(r"-?\d+(?:,\d+)?(?:·10([⁻⁰¹²³⁴⁵⁶⁷⁸⁹]+))?")
UNSUP = str.maketrans("⁻⁰¹²³⁴⁵⁶⁷⁸⁹", "-0123456789")


def parse_nums(line):
    out = []
    for mm in NUMRE.finditer(line):
        base = float(mm.group(0).split("·")[0].replace(",", "."))
        if mm.group(1):
            base *= 10 ** int(mm.group(1).translate(UNSUP))
        out.append(base)
    return out


def check_zadachi():
    text = (UNIT / "zadachi.md").read_text(encoding="utf-8")
    parts = re.split(r"^### Задача (\d+)\.", text, flags=re.M)
    found = {}
    for num_, body in zip(parts[1::2], parts[2::2]):
        mm = re.search(r"\*\*Відповідь:\*\*(.*)", body)
        assert mm, f"задача {num_}: нема рядка Відповідь"
        found[int(num_)] = parse_nums(mm.group(1))
    assert set(found) == set(ZANS), (sorted(set(found) ^ set(ZANS)))
    bad = []
    for num_, exprs in ZANS.items():
        want = [val(e_) for e_ in exprs]
        got = found[num_]
        if len(got) != len(want):
            bad.append(f"задача {num_}: у рядку {len(got)} чисел {got}, а порахувано {len(want)}")
            continue
        for g_, w_ in zip(got, want):
            if not (abs(g_ - w_) <= 0.01 * abs(w_) or abs(g_ - w_) < 1e-9):
                bad.append(f"задача {num_}: у файлі {g_}, порахувано {w_:.5g}")
    return len(found), bad


