def plain(s: str) -> str:
    def f(m):
        p, q = m.group(1).strip(), m.group(2).strip()
        p = p if re.fullmatch(r"[\w.,²³ⁿ₀-₉]+", p) else f"({p})"
        q = q if re.fullmatch(r"[\w.,²³ⁿ₀-₉]+", q) else f"({q})"
        return f"{p}/{q}"
    return re.sub(r"\[\[\s*(.+?)\s*//\s*(.+?)\s*\]\]", f, s or "").strip()


def tasks(unit: str) -> list[dict]:
    """Задачі з zadachi.md: уся умова до <details> + «**Відповідь:**» з розвʼязання."""
    res, cur, mode = [], None, None
    for raw in (C / unit / "zadachi.md").read_text(encoding="utf-8").splitlines():
        s = raw.strip()
        if raw.startswith("## "):
            cur, mode = None, None
            continue
        m = re.match(r"\*\*(Задача[^*]*)\*\*\s*(.*)", s)
        if m:
            cur = {"title": m.group(1).strip().rstrip("."), "text": plain(m.group(2)), "pre": "", "answer": ""}
            res.append(cur)
            mode = "cond"
            continue
        if cur is None:
            continue
        if mode in ("cond", "code"):
            if s.startswith("<details"):
                mode = "sol"
            elif s.startswith("```"):
                mode = "cond" if mode == "code" else "code"
            elif mode == "code":
                cur["pre"] += raw + "\n"
            elif s:
                cur["text"] += "\n" + plain(s)
        elif mode == "sol":
            a = re.match(r"\*\*Відповідь:?\*\*:?\s*(.*)", s)
            if a and not cur["answer"]:
                cur["answer"] = plain(a.group(1))
    return res


