QS = []


def _base(topic, q, explain, src):
    return {"id": f"zfp-{len(QS) + 1:03d}", "topic": topic, "q": q, "explain": explain, "src": src}


def _place(right, wrong):
    """Правильний варіант не завжди перший: зсув за номером питання."""
    opts = [right] + list(wrong)
    k = len(QS) % len(opts)
    opts = opts[k:] + opts[:k]
    return opts, opts.index(right)


def T(topic, q, right, wrong, explain, src, keep=False):
    d = _base(topic, q, explain, src)
    if keep:
        opts, ans = [right] + list(wrong), 0
        d["keepOrder"] = True
    else:
        opts, ans = _place(right, wrong)
    d.update({"type": "single", "options": opts, "answer": ans})
    QS.append(d)


def NUM(topic, q, py_value, verify, explain, src, tol=0.01, sig=4, agree=1e-6):
    """py_value - пораховано python тут; verify - незалежний вираз sympy."""
    pb = sv(verify)
    assert close(py_value, pb, agree), (q, py_value, pb)
    d = _base(topic, q, explain, src)
    d.update({"type": "number", "answer": rnd(py_value, sig), "tol": tol, "calc": True, "verify": verify})
    QS.append(d)


def CS(topic, q, exprs, labels, verify, explain, src):
    """exprs[0] - правильне значення (рядок sympy), решта - типові помилки; labels - як показати."""
    vals = [sv(e_) for e_ in exprs]
    assert close(vals[0], sv(verify), 1e-9), (q, vals[0], sv(verify))
    for vv in vals[1:]:
        assert not close(vv, vals[0], 1e-6), (q, "дистрактор = відповідь")
    assert len(set(labels)) == len(labels), labels
    pairs = list(zip(labels, exprs))
    k = len(QS) % len(pairs)
    pairs = pairs[k:] + pairs[:k]
    d = _base(topic, q, explain, src)
    d.update({"type": "single", "options": [p[0] for p in pairs], "answer": [p[1] for p in pairs].index(exprs[0]),
              "calc": True, "verify": verify, "value": exprs[0], "optionValues": [p[1] for p in pairs]})
    QS.append(d)


