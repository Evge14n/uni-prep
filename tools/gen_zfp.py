def fmt(xv, nd):
    return f"{xv:.{nd}f}".replace(".", ",")


def rnd(xv, sig=4):
    return float(f"{xv:.{sig}g}")


def up(xv, sig):
    """Похибку округлюємо у більший бік до sig значущих цифр."""
    e = math.floor(math.log10(abs(xv))) - sig + 1
    return math.ceil(round(xv / 10 ** e, 9)) * 10 ** e


def one(theta, h):
    """Похибка одного відліку: (9) 2θ/3 і (10) 0,95h/2, квадратично (11)."""
    return math.hypot(2 * theta / 3, 0.95 * h / 2)


def stud(xs):
    """Середнє і випадкова похибка (ф-ли 1, 4, 6), t = 2,78."""
    n = len(xs)
    mean = sum(xs) / n
    return mean, 2.78 * math.sqrt(sum((x - mean) ** 2 for x in xs) / (n * (n - 1)))


