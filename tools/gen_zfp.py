def sv(expr):
    """Значення рядка sympy (так само, як у verify_quizzes.py)."""
    return float(sp.N(sp.sympify(eval(expr, {"__builtins__": {}}, NS)), 20))  # noqa: S307 - лише наші рядки


def close(p, q, rel):
    return abs(p - q) <= rel * max(abs(q), 1e-300)


