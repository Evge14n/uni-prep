def check_zadachi():
    text = (OUT / "zadachi.md").read_text(encoding="utf-8")
    parts = re.split(r"^## ", text, flags=re.M)[1:]
    errs = []
    exp = zad_expected()
    for head, want in exp.items():
        sec = [p for p in parts if p.startswith(head)]
        if len(sec) != 1:
            errs.append(f"zadachi.md: розділ «{head}» знайдено {len(sec)} разів")
            continue
        ans = [ln for ln in sec[0].splitlines() if ln.startswith("**Відповідь:**")]
        if len(ans) != 1:
            errs.append(f"zadachi.md «{head}»: рядків «Відповідь» {len(ans)}")
            continue
        for w in want:
            if w not in ans[0]:
                errs.append(f"zadachi.md «{head}»: у відповіді нема «{w}» (є: {ans[0]})")
    return errs


def check_md():
    errs, warn = [], []
    for f in sorted(OUT.glob("*.md")) + [OUT / "meta.json"]:
        t = f.read_text(encoding="utf-8")
        for b in BAD:
            if b in t:
                errs.append(f"{f.name}: заборонене «{b}»")
        if f.suffix == ".md":
            inside = False
            for i, ln in enumerate(t.splitlines(), 1):
                if ln.startswith("```"):
                    inside = not inside
                    continue
                if inside and len(ln) > 42:
                    warn.append(f"{f.name}:{i}: рядок у блоці коду {len(ln)} символів")
    # список імен для перевірки - локальний файл поза репо (у публічному репо імен нема)
    _nf = Path(r"D:\Універ\00_Загальне\_імена-не-на-сайт.txt")
    _names = [x.strip() for x in _nf.read_text(encoding="utf-8").split(",") if x.strip()] if _nf.exists() else []
    for name in _names:
        for f in sorted(OUT.glob("*.md")) + [OUT / "meta.json"]:
            if name in f.read_text(encoding="utf-8"):
                errs.append(f"{f.name}: прізвище/ім'я «{name}» не можна на сайт")
    return errs, warn


def self_check(qs):
    errs = []
    ids = [q["id"] for q in qs]
    if len(ids) != len(set(ids)):
        errs.append("дублікати id")
    for q in qs:
        if q["type"] == "single":
            if not (0 <= q["answer"] < len(q["options"])):
                errs.append(f"{q['id']}: індекс поза варіантами")
            if len(set(q["options"])) != len(q["options"]):
                errs.append(f"{q['id']}: однакові варіанти")
        if q.get("calc") and "verify" not in q:
            errs.append(f"{q['id']}: calc без verify")
        s = json.dumps(q, ensure_ascii=False)
        for b in BAD:
            if b in s:
                errs.append(f"{q['id']}: заборонене «{b}»")
    return errs


def check_file(path):
    """Звіряє quiz.json (або копію) з даними генератора: кожне питання цілком."""
    want = {q["id"]: q for q in build_questions()}
    have = json.loads(Path(path).read_text(encoding="utf-8"))["questions"]
    errs = self_check(have)
    if len(have) < 70:
        errs.append(f"мало питань: {len(have)}")
    for q in have:
        w = want.get(q["id"])
        if w is None:
            errs.append(f"{q['id']}: нема в даних генератора")
            continue
        for k in sorted(set(q) | set(w)):
            if q.get(k) != w.get(k):
                errs.append(f"{q['id']}: поле «{k}» = {q.get(k)!r} ≠ еталон {w.get(k)!r}")
    missing = set(want) - {q["id"] for q in have}
    if missing:
        errs.append(f"бракує питань: {sorted(missing)}")
    return errs


