"""Генерує content/plan.md: план до колоквіумів і сесії у форматі «Т мінус N днів».
Норма 30-40 хв на день. Скрипт сам перевіряє хвилини (assert) і що кожна тема колоквіумів є в плані.
Запуск: python -P -E tools/make_plan.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = ROOT / "content"


def topics(unit):
    q = json.loads((C / unit / "quiz.json").read_text(encoding="utf-8"))["questions"]
    out = []
    for x in q:
        if x["topic"] not in out:
            out.append(x["topic"])
    return out


AN = topics("an-k1")
MA = topics("ma-k2")

# Блок А (щодня): повторення карток у боті або режим «Пригадай сам» - 10-15 хв.
# Блок Б (вт-пт): одна тема - 20-25 хв: теорія теми + 1 задача письмово + 8-10 питань тренування.
A_MIN, B_MIN = 12, 25
WEEK = [
    ("пн", "А", A_MIN),            # 4 пари + ЛР - лише блок А
    ("вт", "А+Б", A_MIN + B_MIN),
    ("ср", "А+Б", A_MIN + B_MIN),
    ("чт", "А+Б", A_MIN + B_MIN),  # день матану: задача або доведення з матану письмово
    ("пт", "А+Б", A_MIN + B_MIN),
    ("сб", "А+тест", A_MIN + 15),  # пробний тест з таймером 15 хв
    ("нд", "легко", 10),
]
for d, _, m in WEEK:
    assert m <= 40, (d, m)
assert sum(m for _, _, m in WEEK) <= 7 * 40

# черга тем для блоку Б: по черзі аналітична / матан, у четвер - матан
queue = []
ai = mi = 0
lesson = 0
while ai < len(AN) or mi < len(MA):
    day = WEEK[1 + (lesson % 4)][0]
    take_ma = (day == "чт") or (lesson % 2 == 1)
    if (take_ma and mi < len(MA)) or ai >= len(AN):
        queue.append(("ma-k2", "Матан К2", MA[mi], day)); mi += 1
    else:
        queue.append(("an-k1", "Аналітична К1", AN[ai], day)); ai += 1
    lesson += 1
assert {t for u, _, t, _ in queue if u == "an-k1"} == set(AN)
assert {t for u, _, t, _ in queue if u == "ma-k2"} == set(MA)

L = []
w = L.append
w("# План підготовки")
w("")
w("Норма - **30-40 хв на день**, не більше. Дат колоквіумів поки нема, тому план - не за календарем, а")
w("чергою занять і правилом **«Т мінус N днів»**: щойно дізнаєшся дату, рахуй, скільки днів лишилось, і")
w("переходь до розділу «Останній тиждень».")
w("")
w("## Як виглядає день")
w("")
w("| День | Що | Хв |")
w("|---|---|---|")
desc = {
    "А": "лише блок А: повторення",
    "А+Б": "блок А + блок Б (одна тема)",
    "А+тест": "блок А + пробний тест з таймером",
    "легко": "10 хв: перечитати шпаргалку одного колоквіуму",
}
for d, k, m in WEEK:
    extra = " (матан: одна задача або доведення письмово)" if d == "чт" else ""
    w(f"| {d} | {desc[k]}{extra} | {m} |")
w("")
w(f"Разом за тиждень {sum(m for _, _, m in WEEK)} хв (пораховано скриптом, кожен день ≤ 40).")
w("")
w("- **Блок А, 10-15 хв** - зранку, через 30-40 хв після підйому або в дорозі. Спершу повторення")
w("  (картки в боті або на сайті «Тести → Пригадай сам»), потім кілька нових. Після 21:30 нового не")
w("  брати, максимум 5 хв повторення.")
w("- **Блок Б, 20-25 хв** - між 16:00 і 19:00: одна тема з черги нижче. Прочитати тему у вкладці")
w("  «Теорія», одну задачу з «Задач» розвʼязати **письмово** і лише потім відкрити розвʼязання,")
w("  далі «Тести → Тренувати лише вибрані теми» на цю тему (8-10 питань).")
w("- **Відео** - лише якщо задача не вийшла: сайт сам дає посилання з потрібної хвилини після")
w("  неправильної відповіді.")
w("- **Субота** - пробний тест «Як на справжньому» (15 хв) по колоквіуму, тему якого більше пройдено.")
w("")
w("## Черга тем (блок Б)")
w("")
w("| № | День тижня | Колоквіум | Тема | Де |")
w("|---|---|---|---|---|")
for i, (u, name, t, day) in enumerate(queue, 1):
    w(f"| {i} | {day} | {name} | {t} | [теорія](#/u/{u}/teoriya), [задачі](#/u/{u}/zadachi), [тест](#/u/{u}/test) |")
w("")
w(f"Тем {len(queue)}: аналітична {len(AN)}, матан {len(MA)}. При 4 заняттях Б на тиждень - "
  f"≈ {-(-len(queue) // 4)} тижні(в). Якщо колоквіум ближче - див. правило нижче.")
w("")
w("## Останній тиждень перед колоквіумом (Т мінус N)")
w("")
w("| Коли | Що | Хв |")
w("|---|---|---|")
tm = [
    ("Т-7 ... Т-4", "блок Б лише з тем цього колоквіуму, які ще не пройдені; якщо всі пройдені - «Лише помилки»", 37),
    ("Т-3", "пробний тест «Як на справжньому» з таймером + розбір кожної помилки", 35),
    ("Т-2", "шпаргалка колоквіуму + «Лише помилки»", 30),
    ("Т-1", "ще один пробний тест з таймером, потім лише шпаргалка; після 21:30 нічого нового", 30),
    ("Т-0", "зранку 10 хв шпаргалки. Для матану - кодове слово і 15 хв на тест у Moodle", 10),
]
for k, t, m in tm:
    assert m <= 40
    w(f"| {k} | {t} | {m} |")
w("")
w("Якщо днів до колоквіуму менше, ніж тем у черзі: бери в блок Б по дві короткі теми (лише тест на")
w("тему, без задачі), а теми, де в тренуванні вже ≥ 80 %, пропускай.")
w("")
w("## Після колоквіумів: сесія")
w("")
w("Сесія - після 16-17 навчальних тижнів, тобто після 25.12; точні дати іспитів - **уточнити** в")
w("розкладі сесії. Норма та сама, 30-40 хв на день. Порядок - за датою іспиту. На кожен іспит:")
w("")
w("| Коли | Що |")
w("|---|---|")
w("| Т-21 ... Т-8 | по одній темі на день у блоці Б (вкладка «Теорія» + 1 задача + тест на тему); блок А - картки |")
w("| Т-7 ... Т-4 | означення і теореми (вкладка «Означення і теореми»): пригадати вголос, потім звірити |")
w("| Т-3 | пробний тест «Як на справжньому» + розбір |")
w("| Т-2 | «Лише помилки» + шпаргалка |")
w("| Т-1 | ще один пробний тест, далі лише шпаргалка |")
w("")
w("Іспити: [матаналіз](#/u/ma/teoriya), [аналітична](#/u/an/teoriya), [механіка](#/u/mech/teoriya),")
w("[молекулярна](#/u/mol/teoriya). Заліки: [програмування](#/u/prog/teoriya), [ЗФП](#/u/zfp/teoriya),")
w("[історія](#/u/hist/teoriya), [англійська](#/u/eng/teoriya).")
w("")
(C / "plan.md").write_text("\n".join(L), encoding="utf-8")
print(f"plan.md: тем {len(queue)}, тиждень {sum(m for _, _, m in WEEK)} хв, макс. день {max(m for _, _, m in WEEK)} хв")
