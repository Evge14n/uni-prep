"""Генерує content/plan.md: план до колоквіумів і сесії у форматі «Т мінус N днів».
Норма 30-40 хв на день. Скрипт сам перевіряє хвилини (assert) і що кожна тема колоквіумів є в плані.
Запуск: python -P -E tools/make_plan.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = ROOT / "content"


def topics(unit):
    q = json.loads((C / unit / "quiz.json").read_text(encoding="utf-8"))["questions"]
    out = []
    for x in q:
        if x["topic"] not in out:
            out.append(x["topic"])
    return out


AN = topics("an-k1")
MA = topics("ma-k2")

# Блок А (щодня): повторення карток у боті або режим «Пригадай сам» - 10-15 хв.
# Блок Б (вт-пт): одна тема - 20-25 хв: теорія теми + 1 задача письмово + 8-10 питань тренування.
A_MIN, B_MIN, W_MIN = 12, 25, 10
WEEK = [
    ("пн", "А", A_MIN),            # 4 пари + ЛР - лише блок А
    ("вт", "А+Б", A_MIN + B_MIN),
    ("ср", "А+Б", A_MIN + B_MIN),
    ("чт", "А+Б", A_MIN + B_MIN),
    ("пт", "А+Б", A_MIN + B_MIN),
    ("сб", "А+тест", A_MIN + 15),  # пробний тест з таймером колоквіуму
    ("нд", "тиждень", 8 + W_MIN),  # UNIFIX1: короткий блок А + тест тижня з усього вивченого
]
for d, _, m in WEEK:
    assert m <= 40, (d, m)
assert sum(m for _, _, m in WEEK) <= 7 * 40

# UNIFIX1 п.10: черга блоку Б БЕЗ прив'язки до днів тижня - бот іде тією самою чергою (content/plan_queue.json),
# сайт («Сьогодні») показує першу тему черги, де ще < 8 відповідей. Колоквіуми чергуються пропорційно
# кількості тем (рівномірно, а не «спершу один, потім інший») - це і є перемежування.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from topicmap import TASKS  # noqa: E402

queue = []
ai = mi = 0
while ai < len(AN) or mi < len(MA):
    # хто «відстає» від своєї частки - той наступний
    if mi >= len(MA) or (ai < len(AN) and ai / len(AN) <= mi / len(MA)):
        queue.append(("an-k1", "Аналітична К1", AN[ai])); ai += 1
    else:
        queue.append(("ma-k2", "Матан К2", MA[mi])); mi += 1
assert {t for u, _, t in queue if u == "an-k1"} == set(AN)
assert {t for u, _, t in queue if u == "ma-k2"} == set(MA)
for u, _, t in queue:
    assert t in TASKS[u], (u, t)

COLL = {"an-k1": json.loads((C / "an-k1" / "meta.json").read_text(encoding="utf-8")),
        "ma-k2": json.loads((C / "ma-k2" / "meta.json").read_text(encoding="utf-8"))}
TIMER = {u: m["test"]["timer"] for u, m in COLL.items()}

(C / "plan_queue.json").write_text(json.dumps({
    "note": "Черга блоку Б (make_plan.py, UNIFIX1). Бот UniNagad іде нею: тема -> перша незроблена задача з tasks.",
    "queue": [{"n": i, "unit": u, "topic": t, "tasks": TASKS[u][t]} for i, (u, _, t) in enumerate(queue, 1)],
    "timer": TIMER,
}, ensure_ascii=False, indent=1), encoding="utf-8")

L = []
w = L.append
w("# План підготовки")
w("")
w("Норма - **30-40 хв на день**, не більше. Дат колоквіумів поки нема, тому план - не за календарем, а")
w("чергою занять і правилом **«Т мінус N днів»**: щойно дізнаєшся дату, рахуй, скільки днів лишилось, і")
w("переходь до розділу «Останній тиждень».")
w("")
w("## Чому вчимо так: щоб памʼятати і через місяць")
w("")
w("Коротка памʼять обманює: одразу після читання все здається знайомим, а через тиждень зникає. Люди")
w("вважають «прочитав підряд» кращим навіть тоді, коли їхній власний тест показав протилежне (Kornell, Bjork 2008).")
w("Тому «памʼятаю надовго» рахуємо лише за правильну відповідь **через добу і більше**, а не того ж дня: тест через")
w("1+ добу дає найбільший виграш, g = 0,69, і «пригадай сам» вдвічі сильніший за «вибери варіант», 0,61 проти 0,29")
w("(Rowland 2014). Кілька повторень у різні дні тримають понад 60 % понять через 24 дні після іспиту проти менше 20 %")
w("(Rawson, Dunlosky 2011), а змішані типи задач з математики дають g = 0,34 (Brunmair, Richter 2019). Звідси картки «поясни, чому» і")
w("«виведи», задачі без підказки, тест тижня в неділю і тест «через місяць». Джерела з DOI - у бібліотеці Навчання-ЛНУ, ПАМʼЯТЬ-І-НАВЧАННЯ.md.")
w("")
w("## Як виглядає день")
w("")
w("| День | Що | Хв |")
w("|---|---|---|")
desc = {
    "А": "лише блок А: повторення",
    "А+Б": "блок А + блок Б (наступна тема з черги)",
    "А+тест": "блок А + пробний тест з таймером",
    "тиждень": "короткий блок А + тест тижня: 10 хв з усього вивченого, теми впереміш",
}
for d, k, m in WEEK:
    w(f"| {d} | {desc[k]} | {m} |")
w("")
w(f"Разом за тиждень {sum(m for _, _, m in WEEK)} хв (пораховано скриптом, кожен день ≤ 40).")
w("")
w("- **Блок А, 10-15 хв** - зранку, через 30-40 хв після підйому або в дорозі. Картки в боті UniNagad: спершу")
w("  повторення (теми впереміш), потім кілька нових. Прогрес карток веде лише бот. Режим «Пригадай сам» на сайті -")
w("  окремий, коли бота нема під рукою. Після 21:30 нового не брати, максимум 5 хв повторення.")
w("- **Блок Б, 20-25 хв** - вт-пт між 16:00 і 19:00: **наступна тема з черги нижче**, без прив'язки до дня тижня")
w("  (бот іде тією самою чергою). Прочитати тему у вкладці «Теорія», одну задачу з «Задач» розвʼязати **письмово**")
w("  і лише потім відкрити розвʼязання, далі «Тести → Тренувати лише вибрані теми» на цю тему (8-10 питань).")
w("- **Відео** - лише якщо задача не вийшла: сайт сам дає посилання з потрібної хвилини після")
w("  неправильної відповіді.")
w(f"- **Субота** - пробний тест «Як на справжньому» по колоквіуму, тему якого більше пройдено (аналітична {TIMER['an-k1']} хв, матан {TIMER['ma-k2']} хв).")
w("- **Неділя** - тест тижня: 10 хв, картки з усього, що вже вчив, теми впереміш. Раз на 4 тижні замість нього -")
w("  тест «через місяць» з того, що вчив місяць тому. Колоквіум минув - картки не зникають, а йдуть у підтримку:")
w("  рідкі повторення через тижні й місяці, до сесії і далі.")
w("")
w("## Черга тем (блок Б)")
w("")
w("| № | Колоквіум | Тема | Задачі | Де |")
w("|---|---|---|---|---|")
for i, (u, name, t) in enumerate(queue, 1):
    tk = ", ".join(str(n) for n in TASKS[u][t]) or "- (лише тест на тему)"
    w(f"| {i} | {name} | {t} | {tk} | [теорія](#/u/{u}/teoriya), [задачі](#/u/{u}/zadachi), [тест](#/u/{u}/test) |")
w("")
w(f"Тем {len(queue)}: аналітична {len(AN)}, матан {len(MA)}. При 4 заняттях Б на тиждень - "
  f"≈ {-(-len(queue) // 4)} тижні(в). Якщо колоквіум ближче - див. правило нижче.")
w("")
w("## Останній тиждень перед колоквіумом (Т мінус N)")
w("")
w("| Коли | Що | Хв |")
w("|---|---|---|")
tm = [
    ("Т-7 ... Т-4", "блок Б лише з тем цього колоквіуму, які ще не пройдені; якщо всі пройдені - «Лише помилки»", 37),
    ("Т-3", "пробний тест «Як на справжньому» з таймером + розбір кожної помилки", 35),
    ("Т-2", "шпаргалка колоквіуму + «Лише помилки»", 30),
    ("Т-1", "ще один пробний тест з таймером, потім лише шпаргалка; після 21:30 нічого нового", 30),
    ("Т-0", "зранку 10 хв шпаргалки. Для матану - кодове слово і 15 хв на тест у Moodle", 10),
]
for k, t, m in tm:
    assert m <= 40
    w(f"| {k} | {t} | {m} |")
w("")
w("Якщо днів до колоквіуму менше, ніж тем у черзі: бери в блок Б по дві короткі теми (лише тест на")
w("тему, без задачі), а теми, де в тренуванні вже ≥ 80 %, пропускай.")
w("")
w("## Після колоквіумів: сесія")
w("")
w("Сесія - після 16-17 навчальних тижнів, тобто після 25.12; точні дати іспитів - **уточнити** в")
w("розкладі сесії. Норма та сама, 30-40 хв на день. Порядок - за датою іспиту. На кожен іспит:")
w("")
w("| Коли | Що |")
w("|---|---|")
w("| Т-21 ... Т-8 | по одній темі на день у блоці Б (вкладка «Теорія» + 1 задача + тест на тему); блок А - картки |")
w("| Т-7 ... Т-4 | означення і теореми (вкладка «Означення і теореми»): пригадати вголос, потім звірити |")
w("| Т-3 | пробний тест «Як на справжньому» + розбір |")
w("| Т-2 | «Лише помилки» + шпаргалка |")
w("| Т-1 | ще один пробний тест, далі лише шпаргалка |")
w("")
w("Іспити: [матаналіз](#/u/ma/teoriya), [аналітична](#/u/an/teoriya), [механіка](#/u/mech/teoriya),")
w("[молекулярна](#/u/mol/teoriya). Заліки: [програмування](#/u/prog/teoriya), [ЗФП](#/u/zfp/teoriya),")
w("[історія](#/u/hist/teoriya), [англійська](#/u/eng/teoriya).")
w("")
(C / "plan.md").write_text("\n".join(L), encoding="utf-8")
